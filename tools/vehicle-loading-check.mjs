import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
let release;const gate=new Promise(r=>release=r);
await page.route('**/porsche-detailed.glb',async route=>{await gate;await route.continue();});
await page.goto(process.env.TEST_URL||'http://127.0.0.1:4173/',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.__velocity,null,{timeout:120000});
await page.click('#nextCar');
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().assetStatus),'loading');
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),0);
assert.ok(await page.locator('#menuPreview').evaluate(e=>e.classList.contains('vehicle-loading')));
await page.click('#vehicleBtn');
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),0);
assert.match(await page.locator('#vehicleInfo').innerText(),/正在载入/);
await page.click('#vehicleBack');await page.click('#prevCar');release();
await page.waitForTimeout(1000);
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().car),'458');
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),1);
await page.click('#nextCar');
await page.waitForFunction(()=>window.__velocity.snapshot().assetStatus==='ready',null,{timeout:120000});
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),1);
assert.ok(!await page.locator('#menuPreview').evaluate(e=>e.classList.contains('vehicle-loading')));
let releaseF40;const f40Gate=new Promise(r=>releaseF40=r);
await page.route('**/f40-detailed.glb',async route=>{await f40Gate;await route.continue();});
await page.click('#nextCar');await page.click('#navTrack');releaseF40();
await page.waitForFunction(()=>window.__velocity.snapshot().assetStatus==='ready',null,{timeout:120000});
assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),0);
assert.ok(!await page.locator('#menuPreview').evaluate(e=>e.classList.contains('vehicle-loading')));
await page.click('#navCar');assert.equal(await page.evaluate(()=>window.__velocity.snapshot().sceneVisibility.cars),1);
assert.deepEqual(errors,[]);await browser.close();
console.log('PASS: no old models during loading in garage or inspection; stale completion preserves selected car and city preview');
